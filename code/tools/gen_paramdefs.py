"""Generate eldendisk/extension/innovate_spells/paramdefs.py from a Paramdex checkout (developer tool, not shipped).

    python tools/gen_paramdefs.py <Paramdex>/ER/Defs

Writes two files: the five tables of innovate-spells and game/paramlayouts.py (six tables, for `read --param`).

Only the facts the package needs are kept: for each of the five tables the row size and, per field, the type, byte offset,
size, bit position / width and array length. Descriptions are not copied. dummy8 padding fields are left out."""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

TABLES = {"goods": "EquipParamGoods", "magic": "MagicParam", "sp": "SpEffect", "shop": "ShopLineupParam", "bullet": "BulletParam"}
SIZES = {"s8": 1, "u8": 1, "dummy8": 1, "s16": 2, "u16": 2, "s32": 4, "u32": 4, "f32": 4, "b32": 4}


def parse(path: Path):
    root = ET.parse(path).getroot()
    fields, off, bit_unit = [], 0, None
    for f in root.find("Fields"):
        m = re.match(r"(\w+)\s+(\w+)(?:\[(\d+)\])?(?::(\d+))?(?:\s*=\s*(\S+))?$", f.get("Def").strip())
        t, name, arr, bits, _ = m.groups()
        if t in ("fixstr", "fixstrW"):
            size = int(arr) * (2 if t == "fixstrW" else 1)
            bit_unit = None
            fields.append((name, t, off, size, 0, 0, int(arr)))
            off += size
        elif bits:
            bits, sz = int(bits), SIZES[t]
            if bit_unit and SIZES[bit_unit[0]] == sz and bit_unit[2] + bits <= sz * 8:
                bpos, base = bit_unit[2], bit_unit[1]
                bit_unit = (t, base, bpos + bits)
            else:
                base, bpos = off, 0
                off += sz
                bit_unit = (t, base, bits)
            fields.append((name, t, base, sz, bpos, bits, 1))
        else:
            n = int(arr) if arr else 1
            sz = SIZES[t] * n
            bit_unit = None
            fields.append((name, t, off, sz, 0, 0, n))
            off += sz
    return off, [x for x in fields if x[1] != "dummy8"]


def main(defs_dir: str, out: str) -> None:
    lines = ['"""GENERATED by tools/gen_paramdefs.py from Paramdex (ER, 1.17.1 layout). Do not edit by hand.',
             '',
             'name -> (type, byte offset, size, bit position, bit width, array length) for the tables innovate-spells edits."""',
             '', 'PARAMDEFS = {']
    for key, xml in TABLES.items():
        size, fields = parse(Path(defs_dir) / (xml + ".xml"))
        lines.append('    %r: {"size": %d, "fields": {' % (key, size))
        for name, t, o, sz, bp, bw, arr in fields:
            lines.append('        %r: (%r, %d, %d, %d, %d, %d),' % (name, t, o, sz, bp, bw, arr))
        lines.append('    }},')
    lines.append('}')
    Path(out).write_text("\n".join(lines) + "\n", encoding="utf-8")


# The running-game reader (eldendisk/game) may not import the extension package, so it gets its own generated file with the
# six tables of the params workbench. Names are the ones typed on the command line (`params.Magic.6230.mp`).
GAME_TABLES = {"Goods": ("EquipParamGoods", "EquipParamGoods"), "Magic": ("Magic", "MagicParam"),
               "SpEffect": ("SpEffectParam", "SpEffect"), "Bullet": ("BulletParam", "BulletParam"),
               "AtkParam_Pc": ("AtkParam_Pc", "AtkParam"), "ShopLineup": ("ShopLineupParam", "ShopLineupParam")}


def main_game(defs_dir: str, out: str) -> None:
    lines = ['"""GENERATED by tools/gen_paramdefs.py from Paramdex (ER, 1.17.1 layout). Do not edit by hand.',
             '',
             'name -> (type, byte offset, size, bit position, bit width, array length) of every field of the six tables of',
             'the params workbench. "param" is the table\'s name in the game."""',
             '', 'LAYOUTS = {']
    for key, (param, xml) in GAME_TABLES.items():
        size, fields = parse(Path(defs_dir) / (xml + ".xml"))
        lines.append('    %r: {"param": %r, "size": %d, "fields": {' % (key, param, size))
        for name, t, o, sz, bp, bw, arr in fields:
            lines.append('        %r: (%r, %d, %d, %d, %d, %d),' % (name, t, o, sz, bp, bw, arr))
        lines.append('    }},')
    lines.append('}')
    Path(out).write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    root = Path(__file__).resolve().parent.parent / "eldendisk"
    main(sys.argv[1], str(root / "extension/innovate_spells/paramdefs.py"))
    main_game(sys.argv[1], str(root / "game/paramlayouts.py"))
