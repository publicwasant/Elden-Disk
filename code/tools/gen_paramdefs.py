"""Generate eldendisk/creative/innovate_spells/paramdefs.py from a Paramdex checkout (developer tool, not shipped).

    python tools/gen_paramdefs.py <Paramdex>/ER/Defs

    python tools/gen_paramdefs.py <Paramdex>/ER/Defs <the game's regulation.bin>

The first writes the five tables innovate-spells builds (creative/innovate_spells/paramdefs.py); the second (1.8.0 part 4) every
table of the game for `read` / `write params.<Table>.<id>.<field>` (game/paramlayouts.py).

Only the facts the package needs are kept: for each of the five tables the row size and, per field, the type, byte offset,
size, bit position / width and array length. Descriptions are not copied. dummy8 padding fields are left out."""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

TABLES = {"goods": "EquipParamGoods", "magic": "MagicParam", "sp": "SpEffect", "shop": "ShopLineupParam", "bullet": "BulletParam", "atk": "AtkParam"}
SIZES = {"s8": 1, "u8": 1, "dummy8": 1, "s16": 2, "u16": 2, "s32": 4, "u32": 4, "f32": 4, "b32": 4}


def parse(path: Path):
    root = ET.parse(path).getroot()
    fields, off, bit_unit = [], 0, None
    for f in root.find("Fields"):
        m = re.match(r"(\w+)\s+(\w+)(?:\[(\d+)\])?(?::(\d+))?(?:\s*=\s*(\S+))?$", f.get("Def").strip())
        t, name, arr, bits, _ = m.groups()
        if t in ("fixstr", "fixstrW"):
            size = int(arr) * (2 if t == "fixstrW" else 1)
            bit_unit = None
            fields.append((name, t, off, size, 0, 0, int(arr)))
            off += size
        elif bits:
            bits, sz = int(bits), SIZES[t]
            if bit_unit and SIZES[bit_unit[0]] == sz and bit_unit[2] + bits <= sz * 8:
                bpos, base = bit_unit[2], bit_unit[1]
                bit_unit = (t, base, bpos + bits)
            else:
                base, bpos = off, 0
                off += sz
                bit_unit = (t, base, bits)
            fields.append((name, t, base, sz, bpos, bits, 1))
        else:
            n = int(arr) if arr else 1
            sz = SIZES[t] * n
            bit_unit = None
            fields.append((name, t, off, sz, 0, 0, n))
            off += sz
    return off, [x for x in fields if x[1] != "dummy8"]


def main(defs_dir: str, out: str) -> None:
    lines = ['"""GENERATED by tools/gen_paramdefs.py from Paramdex (ER, 1.17.1 layout). Do not edit by hand.',
             '',
             'name -> (type, byte offset, size, bit position, bit width, array length) for the tables innovate-spells edits."""',
             '', 'PARAMDEFS = {']
    for key, xml in TABLES.items():
        size, fields = parse(Path(defs_dir) / (xml + ".xml"))
        lines.append('    %r: {"size": %d, "fields": {' % (key, size))
        for name, t, o, sz, bp, bw, arr in fields:
            lines.append('        %r: (%r, %d, %d, %d, %d, %d),' % (name, t, o, sz, bp, bw, arr))
        lines.append('    }},')
    lines.append('}')
    Path(out).write_text("\n".join(lines) + "\n", encoding="utf-8")


# The running-game reader (eldendisk/game) may not import the creative package, so it gets its own generated file: since 1.8.0 part 4
# EVERY table of the game's regulation.bin, by the name the file gives it (`params.NpcParam.10000000.hp`), with the facts of the original
# file that tell its tables apart in memory (the param type, the rows, the first and last row id).
SINGLE_ROW_PAD = 16          # a table of one row: the file pads the row; the def may be shorter by less than this
DIGEST_MAX = 1 << 16         # tables up to this many bytes of rows get a digest of them: tables of the same type, rows and ids differ by it


def table_facts(regulation: str) -> list[dict]:
    """Every .param file of a regulation.bin: name, param type, row size (the step between two rows), rows, first and last id."""
    import struct
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
    from eldendisk.creative.innovate_spells import container
    from eldendisk.creative.innovate_spells.build import Source
    from eldendisk.creative.innovate_spells.container import Bnd4
    bnd = Bnd4(Source(container.decrypt(Path(regulation).read_bytes())).body)
    out = []
    for e in bnd.entries:
        name = Path(str(e.name).replace("\\", "/")).stem
        d = e.data
        toff = struct.unpack_from("<Q", d, 0x10)[0]
        ptype = d[toff:d.index(b"\0", toff)].decode("ascii")
        count = struct.unpack_from("<H", d, 0x0A)[0]
        recs = [struct.unpack_from("<iIQQ", d, 0x40 + 24 * i) for i in range(count)]
        stride = (recs[1][2] - recs[0][2]) if count > 1 else (struct.unpack_from("<I", d, 0)[0] - recs[0][2] if count else 0)
        digest = None
        if count > 1 and count * stride <= DIGEST_MAX:
            import hashlib
            digest = hashlib.sha256(b"".join(d[r[2]:r[2] + stride] for r in recs)).hexdigest()[:16]
        out.append({"name": name, "type": ptype, "stride": stride, "rows": count,
                    "first": recs[0][0] if recs else None, "last": recs[-1][0] if recs else None, "digest": digest})
    return out


def main_game(defs_dir: str, regulation: str, out: str) -> None:
    import hashlib
    import xml.etree.ElementTree as ET
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
    from eldendisk.creative.innovate_spells import bases
    if hashlib.sha256(Path(regulation).read_bytes()).hexdigest() != bases.BASES[bases.CURRENT_BASE]:
        # The rows, ids and digests name the tables in memory: they must be the game's own (a build adds rows; during a `run`
        # the game folder holds the build, the original is in the vault: <vault>\<snapshot>\bin\regulation.bin).
        sys.exit(f"{regulation} is not the game's original {bases.CURRENT_BASE} regulation.bin (a build is swapped in?)")
    by_type = {}
    for x in sorted(Path(defs_dir).glob("*.xml")):
        by_type.setdefault(ET.parse(x).getroot().findtext("ParamType"), []).append(x)
    lines = ['"""GENERATED by tools/gen_paramdefs.py from Paramdex (ER) and the game\'s own regulation.bin (1.17.1). Do not edit by hand.',
             '',
             'Every table of the game, by the name its regulation.bin gives it: "type" (the param type the file names), "size" (the bytes',
             'of a row the layout knows), "stride" (the step between two rows in the file), "rows", "first" and "last" (row ids of the',
             'original file: they tell tables of the same type apart in memory), "digest" (sha256 of the rows of a small table, for the',
             'same purpose) and "fields": name -> (type, byte offset, size, bit position, bit width, array length). "fields" is None',
             'for a table whose Paramdex def does not fit the game\'s rows ("why")."""',
             '', 'LAYOUTS = {']
    fit = 0
    for t in table_facts(regulation):
        best, why = None, f"no Paramdex def for {t['type']}"
        for x in by_type.get(t["type"], []):
            size, fields = parse(x)
            if size == t["stride"] or (t["rows"] <= 1 and size <= t["stride"] < size + SINGLE_ROW_PAD):
                best = (size, fields)
                break
            why = f"the game's rows are {t['stride']} bytes, the Paramdex def of {t['type']} knows {size}"
        head = '    %r: {"type": %r, "stride": %d, "rows": %d, "first": %r, "last": %r, "digest": %r, ' % (
            t["name"], t["type"], t["stride"], t["rows"], t["first"], t["last"], t["digest"])
        if best is None:
            lines.append(head + '"size": None, "why": %r, "fields": None},' % why)
            continue
        fit += 1
        lines.append(head + '"size": %d, "fields": {' % best[0])
        for name, ft, o, sz, bp, bw, arr in best[1]:
            lines.append('        %r: (%r, %d, %d, %d, %d, %d),' % (name, ft, o, sz, bp, bw, arr))
        lines.append('    }},')
    lines.append('}')
    Path(out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{out}: {fit} tables with fields")


if __name__ == "__main__":
    root = Path(__file__).resolve().parent.parent / "eldendisk"
    if len(sys.argv) == 3:            # python tools/gen_paramdefs.py <Paramdex>/ER/Defs <the game's regulation.bin>: the game's tables only
        main_game(sys.argv[1], sys.argv[2], str(root / "game/paramlayouts.py"))
    else:                             # python tools/gen_paramdefs.py <Paramdex>/ER/Defs: the five tables of innovate-spells
        main(sys.argv[1], str(root / "creative/innovate_spells/paramdefs.py"))
